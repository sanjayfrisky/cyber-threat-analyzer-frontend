
"use client";

import { FormEvent, useState } from "react";
import {
  ArrowUp,
  Bot,
  UserRound,
  LoaderCircle,
  RotateCcw,
} from "lucide-react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import rehypeSanitize from "rehype-sanitize";

import type { ChatMessage } from "@/lib/types";
import { sendChat } from "@/lib/api";

const starter = [
  "Explain CVE-2021-44228 and its remediation",
  "What is the difference between CVSS and exploitability?",
  "How should a SOC analyst triage a suspicious PowerShell command?",
];

export function ChatPanel() {
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [prompt, setPrompt] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [sessionId] = useState(() => `web-${Date.now()}`);

  async function submit(e?: FormEvent, preset?: string) {
    e?.preventDefault();

    const question = (preset ?? prompt).trim();

    if (!question || busy) return;

    setError("");
    setPrompt("");
    setBusy(true);

    const user: ChatMessage = {
      id: crypto.randomUUID(),
      role: "user",
      content: question,
    };

    const answerId = crypto.randomUUID();

    setMessages((old) => [
      ...old,
      user,
      { id: answerId, role: "assistant", content: "" },
    ]);

    try {
      await sendChat(question, sessionId, (chunk) => {
        setMessages((old) =>
          old.map((m) =>
            m.id === answerId
              ? { ...m, content: m.content + chunk }
              : m
          )
        );
      });
    } catch (err) {
      const message =
        err instanceof Error
          ? err.message
          : "Unable to contact chat service.";

      setError(message);

      setMessages((old) =>
        old.map((m) =>
          m.id === answerId && !m.content
            ? {
                ...m,
                content:
                  "I couldn't complete this request. Check the backend connection and API logs.",
              }
            : m
        )
      );
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="panel chat-panel">
      <div className="panel-heading">
        <div>
          <div className="eyebrow">KNOWLEDGE ASSISTANT</div>
          <h2>Threat intelligence chat</h2>
          <p>
            Ask questions about CVEs, attack techniques and remediation.
          </p>
        </div>

        <button
          className="icon-button"
          title="Clear conversation"
          onClick={() => {
            if (!busy) {
              setMessages([]);
              setError("");
            }
          }}
        >
          <RotateCcw size={17} />
        </button>
      </div>

      <div className="chat-scroll">
        {messages.length === 0 ? (
          <div className="empty-chat">
            <div className="empty-icon">
              <Bot size={28} />
            </div>

            <h3>What would you like to investigate?</h3>

            <p>
              Responses are generated by your configured backend LLM and RAG
              pipeline.
            </p>

            <div className="suggestions">
              {starter.map((s) => (
                <button key={s} onClick={() => submit(undefined, s)}>
                  {s}
                  <span>↗</span>
                </button>
              ))}
            </div>
          </div>
        ) : (
          <div className="messages">
            {messages.map((m) => (
              <div className={`message ${m.role}`} key={m.id}>
                <div className="avatar">
                  {m.role === "user" ? (
                    <UserRound size={16} />
                  ) : (
                    <Bot size={16} />
                  )}
                </div>

                <div className="message-body">
                  <small>
                    {m.role === "user" ? "YOU" : "CYBERINTEL ASSISTANT"}
                  </small>

                  {m.role === "assistant" && m.content ? (
                    <div className="markdown-content">
                      <ReactMarkdown
                        remarkPlugins={[remarkGfm]}
                        rehypePlugins={[rehypeSanitize]}
                      >
                        {m.content}
                      </ReactMarkdown>
                    </div>
                  ) : (
                    <p>
                      {m.content ||
                        (busy && m.role === "assistant" ? "Thinking…" : "")}
                    </p>
                  )}
                </div>
              </div>
            ))}
          </div>
        )}

        {error && <div className="error-banner">{error}</div>}
      </div>

      <form className="chat-form" onSubmit={submit}>
        <textarea
          value={prompt}
          onChange={(e) => setPrompt(e.target.value)}
          placeholder="Ask about a CVE, threat actor, attack technique..."
          rows={2}
          disabled={busy}
        />

        <button
          className="send-button"
          disabled={busy || !prompt.trim()}
          aria-label="Send message"
        >
          {busy ? (
            <LoaderCircle className="spin" size={19} />
          ) : (
            <ArrowUp size={20} />
          )}
        </button>

        <div className="input-hint">
          Enter to send · Shift + Enter for a new line
        </div>
      </form>
    </section>
  );
}
